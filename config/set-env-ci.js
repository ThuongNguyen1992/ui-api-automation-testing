#!/usr/bin/env node

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

// Fix __dirname in ES module
const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

// Get environment from command line argument
const targetEnv = process.argv[2];

if (!targetEnv) {
  console.log(`
Usage: node config/set-env-ci.js <environment>

Example:
  node config/set-env-ci.js dev
  node config/set-env-ci.js stag
  node config/set-env-ci.js prod
  `);
  process.exit(1);
}

// Path to .env
const targetPath = path.join(__dirname, '../.env.ci');

try {
  const content = `
# Auto generated by set-env script
RUNNER_CI=ci
ENV_CI=${targetEnv}
BROWSER_CI=chrome
`.trimStart();

  fs.writeFileSync(targetPath, content);

  console.log(`✅ .env generated successfully`);
  console.log(`   RUNNER = ci`);
  console.log(`   ENV    = ${targetEnv}`);
  console.log(`   BROWSER= chrome`);

} catch (error) {
  console.error(`❌ Failed to generate .env: ${error.message}`);
  process.exit(1);
}